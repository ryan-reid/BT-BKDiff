(() => {
  const dialog = document.querySelector('#item-revisions-dialog');
  if (!dialog || typeof dialog.showModal !== 'function') return;
  document.documentElement.classList.add('has-item-revisions');
  const labels = {current: 'Current build', changed: 'Updated', added: 'Added', first_recorded: 'First recorded',
    activation_changed: 'Availability changed', removed: 'Removed', reappeared: 'Reappeared',
    recorded_after_gap: 'Source data available', source_gap: 'Source data missing'};
  const select = dialog.querySelector('#item-revision-select');
  const content = dialog.querySelector('#item-revision-content');
  const meta = dialog.querySelector('#item-revision-meta');
  const prevBtn = dialog.querySelector('#item-revision-prev');
  const nextBtn = dialog.querySelector('#item-revision-next');
  const cache = new Map();
  let active = null;
  let request = 0;
  function updateNav() {
    const count = active?.revisions.length || 0;
    const index = Number(select.value);
    prevBtn.disabled = index <= 0;
    nextBtn.disabled = index >= count - 1;
  }
  function renderRevision() {
    const revision = active?.revisions[Number(select.value)];
    if (!revision) return;
    // HTML is generated by the same escaping/highlighting renderer as item cards.
    content.innerHTML = revision.html;
    meta.replaceChildren();
    const link = document.createElement('a');
    link.href = revision.url;
    link.textContent = revision.short_commit;
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    meta.append(document.createTextNode(`${revision.date}${revision.release ? ' · ' + revision.release : ''} · `), link);
    updateNav();
  }
  select.addEventListener('change', renderRevision);
  prevBtn.addEventListener('click', () => {
    if (Number(select.value) > 0) { select.value = String(Number(select.value) - 1); renderRevision(); }
  });
  nextBtn.addEventListener('click', () => {
    if (Number(select.value) < (active?.revisions.length || 1) - 1) { select.value = String(Number(select.value) + 1); renderRevision(); }
  });
  dialog.querySelector('[data-close-revisions]').addEventListener('click', () => dialog.close());
  dialog.addEventListener('close', () => { request++; active = null; });
  dialog.addEventListener('click', event => {
    if (event.target !== dialog) return;
    const rect = dialog.getBoundingClientRect();
    if (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom) dialog.close();
  });
  document.addEventListener('click', async event => {
    if (event.button !== 0 || event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
    const explicit = event.target.closest('[data-revisions-path]');
    const card = event.target.closest('[data-revision-card], .item-index-card, .base-item-card, .set-piece');
    const control = event.target.closest('a, button, input, select, summary, label');
    if (!explicit && (!card || (control && !control.classList.contains('set-th-name')))) return;
    if (!explicit && window.getSelection()?.toString()) return;
    const trigger = explicit || card.querySelector('[data-revisions-path]');
    if (!trigger) return;
    event.preventDefault();
    const token = ++request;
    active = null;
    select.replaceChildren();
    select.disabled = true;
    meta.replaceChildren();
    dialog.querySelector('h2').textContent = 'Item revisions';
    content.textContent = 'Loading revisions…';
    if (!dialog.open) dialog.showModal();
    try {
      const url = new URL((document.body.dataset.siteRoot || './') + trigger.dataset.revisionsPath, location.href).href;
      let data = cache.get(url);
      if (!data) {
        const response = await fetch(url);
        if (!response.ok) throw new Error('Revision request failed');
        data = await response.json();
        cache.set(url, data);
      }
      if (token !== request) return;
      active = data;
      dialog.querySelector('h2').textContent = data.title;
      data.revisions.forEach((revision, index) => {
        const option = document.createElement('option');
        option.value = index;
        option.textContent = `${revision.date} · ${revision.short_commit} · ${revision.kinds.map(kind => labels[kind] || kind.replaceAll('_', ' ')).join(', ')}`;
        select.append(option);
      });
      select.disabled = !data.revisions.length;
      if (data.revisions.length) { select.value = String(data.revisions.length - 1); renderRevision(); }
      else content.textContent = 'No source revisions are available for this item.';
    } catch (error) {
      if (token === request) content.textContent = 'Unable to load revisions. Close this popup and try again.';
    }
  });
})();
